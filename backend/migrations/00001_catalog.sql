    max_hits SMALLINT,
    min_turns SMALLINT,
    max_turns SMALLINT,
    drain SMALLINT,
    healing SMALLINT,
    crit_rate SMALLINT,
    ailment_chance SMALLINT,
    flinch_chance SMALLINT,
    stat_chance SMALLINT,
    stat_changes JSONB,
    target INTEGER REFERENCES move_target (id),
    type elemental_type,
