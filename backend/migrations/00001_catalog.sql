CREATE TYPE elemental_type AS ENUM (
    'GRASS', 'FIRE', 'WATER', 'ELECTRIC', 'ROCK', 'GROUND',
    'FLYING', 'PSYCHIC', 'GHOST', 'POISON', 'FIGHTING', 'DARK',
    'STEEL', 'FAIRY', 'BUG', 'ICE', 'DRAGON', 'NORMAL'
);

CREATE TABLE catalog_snapshot (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_package TEXT NOT NULL CHECK (btrim(source_package) <> ''),
    source_version TEXT NOT NULL CHECK (btrim(source_version) <> ''),
    game_set TEXT NOT NULL CHECK (btrim(game_set) <> ''),
    locale TEXT NOT NULL CHECK (btrim(locale) <> ''),
    lockfile_sha256 TEXT NOT NULL CHECK (lockfile_sha256 ~ '^[0-9a-f]{64}$'),
    manifest_sha256 TEXT NOT NULL UNIQUE CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pokemon (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_snapshot_id INTEGER NOT NULL REFERENCES catalog_snapshot (id),
    slug TEXT NOT NULL CHECK (btrim(slug) <> ''),
    dex_number INTEGER NOT NULL CHECK (dex_number > 0),
    champions_id TEXT,
    name VARCHAR(255) NOT NULL,
    form_name TEXT,
    is_default BOOLEAN NOT NULL,
    is_battle_only_form BOOLEAN NOT NULL,
    is_cosmetic_form BOOLEAN NOT NULL,
    base_species_id INTEGER,
    learnset_known BOOLEAN NOT NULL,
    type1 elemental_type NOT NULL,
    type2 elemental_type,
    base_hp SMALLINT NOT NULL CHECK (base_hp > 0),
    base_atk SMALLINT NOT NULL CHECK (base_atk > 0),
    base_def SMALLINT NOT NULL CHECK (base_def > 0),
    base_spatk SMALLINT NOT NULL CHECK (base_spatk > 0),
    base_spdef SMALLINT NOT NULL CHECK (base_spdef > 0),
    base_speed SMALLINT NOT NULL CHECK (base_speed > 0),
    height SMALLINT CHECK (height > 0),
    weight INTEGER CHECK (weight > 0),
    UNIQUE (catalog_snapshot_id, slug),
    UNIQUE (catalog_snapshot_id, id),
    CHECK (type2 IS NULL OR type2 <> type1),
    CONSTRAINT pokemon_base_species_fk FOREIGN KEY (catalog_snapshot_id, base_species_id)
        REFERENCES pokemon (catalog_snapshot_id, id)
);

COMMENT ON COLUMN pokemon.slug IS 'PokéPC id; stable within the owning snapshot, unlike championsId.';
COMMENT ON COLUMN pokemon.champions_id IS 'Optional upstream championsId; cosmetic forms can share this value.';
COMMENT ON COLUMN pokemon.base_species_id IS 'Mapped from baseSpecies; NULL when the source has no base species. Not a transformation prerequisite.';
COMMENT ON COLUMN pokemon.learnset_known IS 'True when the source explicitly supplies a learnset, including an empty array; false when omitted. No inheritance is inferred.';
COMMENT ON COLUMN pokemon.height IS 'Centimeters; importer must convert if source units differ.';
COMMENT ON COLUMN pokemon.weight IS 'Units of 10 grams (kilograms times 100); importer must convert if source units differ.';

CREATE TABLE pokemon_form_relationship (
    catalog_snapshot_id INTEGER NOT NULL,
    from_pokemon_id INTEGER NOT NULL,
    to_pokemon_id INTEGER NOT NULL,
    PRIMARY KEY (from_pokemon_id, to_pokemon_id),
    CHECK (from_pokemon_id <> to_pokemon_id),
    FOREIGN KEY (catalog_snapshot_id, from_pokemon_id)
        REFERENCES pokemon (catalog_snapshot_id, id),
    FOREIGN KEY (catalog_snapshot_id, to_pokemon_id)
        REFERENCES pokemon (catalog_snapshot_id, id)
);

COMMENT ON TABLE pokemon_form_relationship IS 'Source baseForms edges, from base form to resulting form; not verified Champions transformation conditions.';

CREATE TABLE ability (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_snapshot_id INTEGER NOT NULL REFERENCES catalog_snapshot (id),
    slug TEXT NOT NULL CHECK (btrim(slug) <> ''),
    name VARCHAR(255) NOT NULL,
    effect TEXT NOT NULL,
    effect_short TEXT,
    gen_introduced SMALLINT,
    UNIQUE (catalog_snapshot_id, slug),
    UNIQUE (catalog_snapshot_id, id)
);

CREATE TABLE pokemon_ability (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    catalog_snapshot_id INTEGER NOT NULL,
    pokemon_id INTEGER NOT NULL,
    ability_id INTEGER NOT NULL,
    slot SMALLINT NOT NULL CHECK (slot IN (1, 2, 3)),
    CONSTRAINT pokemon_ability_slot_unique UNIQUE (pokemon_id, slot),
    CONSTRAINT pokemon_ability_pokemon_fk FOREIGN KEY (catalog_snapshot_id, pokemon_id)
        REFERENCES pokemon (catalog_snapshot_id, id),
    CONSTRAINT pokemon_ability_ability_fk FOREIGN KEY (catalog_snapshot_id, ability_id)
        REFERENCES ability (catalog_snapshot_id, id)
);

COMMENT ON COLUMN pokemon_ability.slot IS 'PokéPC ability1 = 1, ability2 = 2, abilityHidden = 3. Preserve source slots, including gaps.';

